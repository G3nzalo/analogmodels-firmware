/*
 * bench.c - instruction counts of the drum voices on a Cortex-M7: the
 * firmware's voice, mixer and FX code compiled with the firmware's flags and
 * run in QEMU (mps2-an500) with -icount, where every instruction takes the
 * same virtual time. An estimate of the CPU cost only (QEMU has no caches,
 * wait states or dual issue). Not part of the firmware.
 *
 * Part of a custom firmware for the Erica Synths LXR-02 (not an official
 * Erica Synths release). Added 2026.
 * SPDX-License-Identifier: GPL-3.0-only
 */
#include <stdio.h>
#include <string.h>
#include "stm32f7xx.h"
#include "Parameters.h"
#include "Preset/InitKit.h"
#include "Soundengine/DSPAudio/DrumVoice.h"
#include "Soundengine/DSPAudio/Snare.h"
#include "Soundengine/DSPAudio/CymbalVoice.h"
#include "Soundengine/DSPAudio/HiHat.h"
#include "Soundengine/DSPAudio/modulationNode.h"
#include "Soundengine/DSPAudio/lfo.h"
#include "Soundengine/DSPAudio/ResonantFilter.h"
#include "Soundengine/MIDI/MidiParser.h"
#include "Soundengine/MIDI/MidiVoiceControl.h"
#include "Soundengine/MIDI/ParameterArray.h"
#include "Soundengine/MIDI/MidiMessages.h"
#include "Soundengine/DSPAudio/AnalogModels.h"
#include "menu/modelPresets.h"
#include "kits_bin.h"	/* generated by build.sh from the .SND kit files */

extern volatile uint32_t bench_sysTickWraps;
extern uint8_t activeParameters[];

static uint64_t ticks(void)
{
	uint32_t w, v;
	do { w = bench_sysTickWraps; v = SysTick->VAL; } while (w != bench_sysTickWraps);
	return (uint64_t)w * 0x1000000ull + (0xFFFFFFu - v);
}

static void setParam(int i, uint8_t val)
{
	MidiMsg msg = {0};
	activeParameters[i] = val;
	if (i < 128) { msg.status = MIDI_CC; msg.data1 = (uint8_t)((i + 1) & 0x7f); }
	else { msg.status = MIDI_CC2; msg.data1 = (uint8_t)((i - 128) & 0x7f); }
	msg.data2 = val;
	midiParser_ccHandler(msg, 1, 0, 0.f);
}
static void applyKit(const uint8_t* p, int n) { for (int i = 0; i < END_OF_SOUND_PARAMETERS; i++) setParam(i, i < n ? p[i] : 0); }

/* the waveform parameter of each voice */
static const int waveParam[6] = { PAR_OSC_WAVE_DRUM1, PAR_OSC_WAVE_DRUM2, PAR_OSC_WAVE_DRUM3,
	PAR_OSC_WAVE_SNARE, PAR_WAVE1_CYM, PAR_WAVE1_HH };
static void setParamCb(uint16_t parNr, uint8_t val) { setParam(parNr, val); }
/* like choosing the waveform in the menu: an 808/909 instrument brings its voice settings */
static void chooseWave(int voice, int wave)
{
	setParam(waveParam[voice], (uint8_t)wave);
	modelPreset_apply((uint8_t)voice, (uint8_t)wave, setParamCb);
}

static int16_t buf[OUTPUT_DMA_SIZE];
static volatile int32_t sink;

static void voiceBlock(int v)
{
	switch (v) {
	case 0: case 1: case 2: calcDrumVoiceAsync((uint8_t)v); calcDrumVoiceSyncBlock((uint8_t)v, buf, OUTPUT_DMA_SIZE); break;
	case 3: Snare_calcAsync(); Snare_calcSyncBlock(buf, OUTPUT_DMA_SIZE); break;
	case 4: Cymbal_calcAsync(); Cymbal_calcSyncBlock(buf, OUTPUT_DMA_SIZE); break;
	default: HiHat_calcAsync(); HiHat_calcSyncBlock(buf, OUTPUT_DMA_SIZE); break;
	}
	sink += buf[7];
}

/* all six voices, like host_render.c / mixer_calcNextSampleBlock() without the FX and mixing */
static void allVoicesBlock(void)
{
	modNode_resetTargets();
	modNode_reassignVeloMod();
	lfo_dispatchNextValue(&voiceArray[0].lfo);
	lfo_dispatchNextValue(&voiceArray[1].lfo);
	lfo_dispatchNextValue(&voiceArray[2].lfo);
	lfo_dispatchNextValue(&snareVoice.lfo);
	lfo_dispatchNextValue(&cymbalVoice.lfo);
	lfo_dispatchNextValue(&hatVoice.lfo);
	SVF_recalcFreq(&voiceArray[0].filter);
	SVF_recalcFreq(&voiceArray[1].filter);
	SVF_recalcFreq(&voiceArray[2].filter);
	SVF_recalcFreq(&snareVoice.filter);
	SVF_recalcFreq(&cymbalVoice.filter);
	SVF_recalcFreq(&hatVoice.filter);
	for (int v = 0; v < 6; v++) voiceBlock(v);
}

void mixer_init(void);
void mixer_calcNextSampleBlock(int16_t* output, int16_t* output2);
static int16_t mixOut[OUTPUT_DMA_SIZE * 2], mixOut2[OUTPUT_DMA_SIZE * 2];

static double insPerTick;

/* instructions per block of one voice, retriggered every 100 blocks */
static double benchVoice(int voice, int blocks)
{
	uint64_t t0 = ticks();
	for (int b = 0; b < blocks; b++) {
		if (b % 100 == 0) voiceControl_noteOn((uint8_t)voice, 60, 127);
		voiceBlock(voice);
	}
	return (ticks() - t0) * insPerTick / blocks;
}

/* the whole audio block: voices, routing, decimation and the FX bus */
static double benchMixer(int blocks)
{
	uint64_t t0 = ticks();
	for (int b = 0; b < blocks; b++) {
		if (b % 100 == 0) for (int v = 0; v < 7; v++) if (v != 5) voiceControl_noteOn((uint8_t)v, 60, 127);
		mixer_calcNextSampleBlock(mixOut, mixOut2);
		sink += mixOut[3];
	}
	return (ticks() - t0) * insPerTick / blocks;
}

static double benchAll(int blocks)
{
	uint64_t t0 = ticks();
	for (int b = 0; b < blocks; b++) {
		if (b % 100 == 0) for (int v = 0; v < 7; v++) if (v != 5) voiceControl_noteOn((uint8_t)v, 60, 127);
		allVoicesBlock();
	}
	return (ticks() - t0) * insPerTick / blocks;
}

int main(void)
{
	SysTick->LOAD = 0xFFFFFF; SysTick->VAL = 0; SysTick->CTRL = 7;
	while (SysTick->VAL == 0) {}	/* wait for the first reload */

	/* calibration: 2 instructions per loop */
	uint64_t t0 = ticks();
	uint32_t n = 4000000;
	__asm volatile ("1: subs %0, %0, #1\n bne 1b" : "+r" (n));
	uint64_t t1 = ticks();
	insPerTick = 8000000.0 / (double)(t1 - t0);
	printf("calibration: %.1f instructions per SysTick tick (expected 40 with -icount shift=0)\n", insPerTick);

	static float nullTarget[4];
	parameterArray_init();
	for (int i = 0; i < END_OF_SOUND_PARAMETERS; i++) if (!parameterArray[i].ptr) parameterArray[i].ptr = nullTarget;
	for (int i = 0; i < 6; i++) modNode_init(&velocityModulators[i]);
	initDrumVoice(); Snare_init(); HiHat_init(); Cymbal_init();
	mixer_init();
	applyKit(&initKit[8], INIT_KIT_SIZE - 8);

	const int N = 3000;
	/* the original waveforms */
	struct { const char* name; int voice; int wave; } cases[] = {
		{"drum  Sin", 0, 0}, {"drum  Tri", 0, 1}, {"drum  Noi", 0, 4}, {"drum  PWM", 0, 5},
		{"snare Tri", 3, 1}, {"cym   Sin", 4, 0}, {"cym   Noi", 4, 4}, {"hat   Sin", 5, 0},
	};
	for (unsigned c = 0; c < sizeof cases / sizeof cases[0]; c++) {
		applyKit(&initKit[8], INIT_KIT_SIZE - 8);
		setParam(waveParam[cases[c].voice], (uint8_t)cases[c].wave);
		benchVoice(cases[c].voice, 200);
		printf("%s  %6.0f instructions/block\n", cases[c].name, benchVoice(cases[c].voice, N));
	}

	/* every 808/909 instrument with its voice settings on a drum voice, the
	 * snare, the cymbal and the hat voice */
	static const char* const modelNames[NUM_ANALOG_MODELS] = { "BD8", "BD9", "SD8", "SD9", "LT8", "MT8",
		"HT8", "LT9", "MT9", "HT9", "LC8", "MC8", "HC8", "RS8", "RS9", "CL8", "CP8", "CP9", "MA8", "CB8",
		"HH8", "HH9", "CY8", "CR9", "RD9" };
	static const int benchVoices[4] = { 0, 3, 4, 5 };
	printf("instrument   drum  snare    cym    hat (instructions/block)\n");
	int worst = MODEL_BD8;
	double worstCost = 0;
	for (int m = MODEL_BD8; m < MODEL_END; m++) {
		printf("%s     ", modelNames[m - MODEL_BD8]);
		for (int k = 0; k < 4; k++) {
			const int v = benchVoices[k];
			applyKit(&initKit[8], INIT_KIT_SIZE - 8);
			chooseWave(v, m);
			benchVoice(v, 200);
			const double cost = benchVoice(v, N);
			if (k == 0 && cost > worstCost) { worstCost = cost; worst = m; }
			printf(" %6.0f", cost);
		}
		printf("\n");
	}

	applyKit(&initKit[8], INIT_KIT_SIZE - 8);
	benchAll(200);
	printf("six voices, %-30s %7.0f instructions/block\n", "init kit (original waveforms)", benchAll(N));
	benchMixer(200);
	printf("whole mixer block (FX on), %-15s %7.0f instructions/block\n", "init kit", benchMixer(N));
	for (unsigned k = 0; k < NUM_BENCH_KITS; k++) {
		applyKit(benchKits[k].params, 247);
		benchAll(200);
		printf("six voices, %-30s %7.0f instructions/block\n", benchKits[k].name, benchAll(N));
		benchMixer(200);
		printf("whole mixer block (FX on), %-15s %7.0f instructions/block\n", benchKits[k].name, benchMixer(N));
	}
	/* worst case: the most expensive instrument on every voice */
	applyKit(&initKit[8], INIT_KIT_SIZE - 8);
	for (int v = 0; v < 6; v++) chooseWave(v, worst);
	char label[40];
	snprintf(label, sizeof label, "%s on all six voices", modelNames[worst - MODEL_BD8]);
	benchAll(200);
	printf("six voices, %-30s %7.0f instructions/block\n", label, benchAll(N));
	for (int fx = 0; fx <= 4; fx++) {
		setParam(PAR_FX_TYPE, (uint8_t)fx); setParam(PAR_FX_DRY_WET, 64);
		benchMixer(200);
		printf("whole mixer block, FX type %d, %s x6       %7.0f instructions/block\n", fx, modelNames[worst - MODEL_BD8], benchMixer(N));
	}
	applyKit(&initKit[8], INIT_KIT_SIZE - 8);
	for (int fx = 1; fx <= 4; fx++) {
		setParam(PAR_FX_TYPE, (uint8_t)fx); setParam(PAR_FX_DRY_WET, 64);
		benchMixer(200);
		printf("whole mixer block, FX type %d,  init kit     %7.0f instructions/block\n", fx, benchMixer(N));
	}
	printf("budget: 216 MHz x 64/44140 s = %.0f cycles per block\n", 216e6 * 64 / 44140.0);
	return 0;
}
