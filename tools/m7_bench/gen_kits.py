"""Writes kits_bin.h with the parameters of the kit files (.SND) in a folder.

usage: gen_kits.py <folder with .SND files> <kits_bin.h>
"""
import os
import sys

N = 247  # END_OF_SOUND_PARAMETERS
folder, out = sys.argv[1], sys.argv[2]
kits = []
if os.path.isdir(folder):
    for f in sorted(os.listdir(folder)):
        if f.upper().endswith(".SND"):
            data = open(os.path.join(folder, f), "rb").read()
            if len(data) == 8 + N:
                kits.append((data[:8].split(b"\0")[0].decode("ascii", "replace"), data[8:]))
lines = ["/* generated by gen_kits.py */", "#include <stdint.h>",
         "static const struct { const char* name; uint8_t params[%d]; } benchKits[] = {" % N]
for name, p in kits:
    lines.append('\t{"%s", {%s}},' % (name, ",".join(str(b) for b in p)))
if not kits:
    lines.append('\t{"none", {0}},')
lines += ["};", "#define NUM_BENCH_KITS %d" % len(kits)]
open(out, "w").write("\n".join(lines) + "\n")
print(f"{out}: {len(kits)} kits")
